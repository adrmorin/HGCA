// Prepares the certificate template used by the certificados-app Node.js service.
//
//   design-assets/certificado/certificado-original.pdf   (2 pages, NOT published)
//        -> certificados-app/src/plantilla.js (page 1 only, {{...}} markers removed,
//           base64 inside an ES module so it deploys together with the app code)
//
// Page 2 of the original is an internal sheet ("NO SE ENVIA AL CLIENTE"), so it
// must never reach the public site. The markers are removed from the text layer
// with plantillaTexto.cjs (taken unchanged from the hcga-registro backend), so a
// PDF search or screen reader never finds a leftover "{{CLIENTE_NOMBRE}}".
//
// Run again whenever the original template changes:  npm run certificado:plantilla
const fs = require('node:fs')
const path = require('node:path')
const { PDFDocument } = require('pdf-lib')
const { eliminarMarcadoresDePagina, mapasDeFuentesDe, textoDeFlujo, flujosYDiccionariosDe } = require('./plantillaTexto.cjs')

const ROOT = path.resolve(__dirname, '..', '..')
const ORIGINAL = path.join(ROOT, 'design-assets', 'certificado', 'certificado-original.pdf')
const SALIDA = path.join(ROOT, 'certificados-app', 'src', 'plantilla.js')

function textoDePagina(pagina, context) {
  return flujosYDiccionariosDe(pagina, context)
    .map((g) => {
      const mapas = mapasDeFuentesDe(g.recursos, context)
      return g.flujos.map((f) => textoDeFlujo(f, mapas)).join('')
    })
    .join('')
}

async function main() {
  const original = await PDFDocument.load(fs.readFileSync(ORIGINAL))
  const doc = await PDFDocument.create()
  const [pagina] = await doc.copyPages(original, [0])
  doc.addPage(pagina)

  const antes = textoDePagina(doc.getPage(0), doc.context)
  const { eliminadas, fuentes } = eliminarMarcadoresDePagina(doc.getPage(0), doc.context)
  const despues = textoDePagina(doc.getPage(0), doc.context)

  if (!antes.includes('{{')) throw new Error('The original template has no {{...}} markers: wrong file?')
  if (despues.includes('{{') || despues.includes('}}')) throw new Error('Markers are still present in the text layer.')
  if (!despues.includes('CERTIFICADO DIGITAL DE')) throw new Error('Institutional text was lost while removing markers.')

  doc.setTitle('Certificado Digital de Intencion Comercial - HCGA Trading LLC')
  doc.setCreator('HCGA Trading LLC')
  doc.setProducer('HCGA Trading LLC')
  const pdf = Buffer.from(await doc.save({ useObjectStreams: false }))
  fs.writeFileSync(SALIDA, `// Generated by scripts/certificado/preparar-plantilla.cjs - do not edit.
export const PLANTILLA_BASE64 = "${pdf.toString('base64')}";
`)

  console.log(`Template: ${path.relative(ROOT, SALIDA)} (1 page, ${eliminadas} marker operations removed, fonts ${fuentes.join(', ')})`)
}

main().catch((e) => {
  console.error(e.message)
  process.exit(1)
})
